#!/usr/bin/env node
// Regenerate web/providers.json: the LLM provider → models catalog used by
// the web UI (secrets provider dropdown, create-agent provider/model
// dropdowns). Snapshots the provider data shipped with the installed
// @earendil-works/pi-coding-agent (pi-ai) package. Re-run after upgrading pi:
//
//   node tools/gen-providers.mjs
//
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// pi-ai may be hoisted or nested under pi-coding-agent depending on the
// install; try both.
const candidates = [
  "node_modules/@earendil-works/pi-ai/dist/providers/data",
  "node_modules/@earendil-works/pi-coding-agent/node_modules/@earendil-works/pi-ai/dist/providers/data",
];
const dataDir = candidates.map((c) => join(root, c)).find((p) => existsSync(p));
if (!dataDir) {
  console.error("pi-ai provider data not found; is @earendil-works/pi-coding-agent installed?");
  process.exit(1);
}

let piVersion = "unknown";
try {
  piVersion = JSON.parse(
    readFileSync(join(root, "node_modules/@earendil-works/pi-coding-agent/package.json"), "utf8"),
  ).version;
} catch {}

const providers = {};
for (const file of readdirSync(dataDir).filter((f) => f.endsWith(".json") && !f.startsWith(".")).sort()) {
  const data = JSON.parse(readFileSync(join(dataDir, file), "utf8"));
  const models = new Map();
  for (const group of Object.values(data)) {
    for (const m of Object.values(group)) {
      if (m.provider && m.id) models.set(m.id, m.name || m.id);
    }
  }
  if (models.size === 0) continue;
  const id = [...Object.values(Object.values(data)[0])][0].provider;
  providers[id] = {
    models: [...models.entries()]
      .map(([mid, name]) => ({ id: mid, name }))
      .sort((a, b) => a.name.localeCompare(b.name)),
  };
}

const out = {
  comment:
    "Generated by tools/gen-providers.mjs from the installed pi package — do not edit by hand. " +
    "Web UI: secrets provider dropdown + create-agent provider/model dropdowns.",
  generated_from: `@earendil-works/pi-coding-agent@${piVersion}`,
  providers,
};

const dest = join(root, "web/providers.json");
writeFileSync(dest, JSON.stringify(out, null, 1) + "\n");
console.log(`wrote ${dest}: ${Object.keys(providers).length} providers, ` +
  `${Object.values(providers).reduce((n, p) => n + p.models.length, 0)} models (pi ${piVersion})`);
